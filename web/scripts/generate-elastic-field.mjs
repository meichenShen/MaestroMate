import { writeFile } from "node:fs/promises";
// Technical SVG displacement texture. R/G encode inverse radial lookup;
// neutral128 outside the lens leaves the original geometry unchanged.
const size = 32,
  rects = [];
for (let y = 0; y < size; y++)
  for (let x = 0; x < size; x++) {
    const dx = ((x + 0.5) / size) * 2 - 1,
      dy = ((y + 0.5) / size) * 2 - 1,
      r2 = dx * dx + dy * dy;
    if (r2 >= 1) continue;
    const falloff = (1 - r2) ** 2;
    const red = Math.round(128 - dx * 114 * falloff),
      green = Math.round(128 - dy * 114 * falloff);
    if (red !== 128 || green !== 128)
      rects.push(
        '<rect x="' +
          x +
          '" y="' +
          y +
          '" width="1" height="1" fill="rgb(' +
          red +
          "," +
          green +
          ',128)"/>',
      );
  }
await writeFile(
  new URL("../public/images/elastic-field.svg", import.meta.url),
  '<svg xmlns="http://www.w3.org/2000/svg" width="32" height="32" viewBox="0 0 32 32"><!-- Generated by scripts/generate-elastic-field.mjs --><path fill="#808080" d="M0 0h32v32H0z"/>' +
    rects.join("") +
    "</svg>\n",
);
